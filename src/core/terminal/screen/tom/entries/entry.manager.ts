import ScreenEntry from "./entry";
import type { EntryUpdateRange, LinesRange } from "../types";

/**
 * Owns the ordered entries that make up TOM's logical screen contents.
 *
 * Each entry represents one cell's complete rendered value. The manager keeps
 * entries in creation order and assigns each a contiguous, one-based range in
 * the logical line sequence. Replacing content, reflowing after a resize, or
 * removing an entry updates the aggregate height and shifts later entry origins
 * as needed. Mutations return affected ranges so the viewport can reconcile
 * only its rendered state against the current logical model.
 *
 * ---------------------------------------------------------------------
 * 🔷 OWNERSHIP AND ORDERING
 * ---------------------------------------------------------------------
 *
 * Entry identity is a stable symbol generated by the entry itself. Updates and
 * removals locate entries by that identity. The backing array is exposed to
 * the viewport through {@link entries} for traversal; it is not a snapshot and
 * must not be mutated outside this manager.
 *
 * ---------------------------------------------------------------------
 * 🔷 LAYOUT BOUNDARY
 * ---------------------------------------------------------------------
 *
 * The manager owns content reflow, entry positions, and total logical line
 * accounting. It does not select visible lines, write terminal rows, clear
 * terminal output, or move the cursor; those tasks belong to the viewport.
 *
 * @internal This class is an implementation detail of the terminal screen.
 * @since 1.0.0
 */
class EntriesManager {
    /**
     * Backing list of entries in creation and logical screen order.
     *
     * Entry mutations must pass through this manager to keep starts and the
     * cached aggregate line count consistent. The viewport reads this array
     * directly but does not own it.
     *
     * @internal
     * @since 1.0.0
     */
    readonly #_entries: ScreenEntry[] = [];

    /**
     * Cached sum of every managed entry's current height.
     *
     * Create, update, remove, refresh, and clear maintain this value. It equals
     * the final one-based boundary after the last logical line, minus one.
     *
     * @internal
     * @since 1.0.0
     */
    #_entriesLines = 0;

    /**
     * Internal accessor used to centralize reads of the aggregate line count.
     *
     * This adds no validation or recalculation; the backing value is maintained
     * by the manager's mutation methods.
     *
     * @returns The cached sum of entry heights.
     *
     * @internal
     * @since 1.0.0
     */
    get #_totalLines() { return this.#_entriesLines; }

    /**
     * Returns the number of entry objects currently managed.
     *
     * This is an entry count, not a line count or visible-row count.
     *
     * @returns The current number of entries.
     *
     * @internal
     * @since 1.0.0
     */
    get number() { return this.#_entries.length; }

    /**
     * Returns the total number of logical lines across all entries.
     *
     * Lines may be outside the current viewport; this value describes the
     * complete model rather than only the visible terminal region.
     *
     * @returns The cached total logical line count.
     *
     * @internal
     * @since 1.0.0
     */
    get totalLines() { return this.#_totalLines; }

    /**
     * Appends an entry after the current final logical line.
     *
     * The new entry starts at `totalLines + 1`, receives a stable symbol
     * identity, and parses its content at the terminal's current width. Its
     * resulting height is added to the manager's cached total. This method
     * changes only the logical model; the caller decides when the viewport is
     * rendered.
     *
     * @param content - Complete rendered content of the new entry.
     * @param options - Optional metadata retained by the entry.
     * @param options.isError - Whether the entry represents error output;
     * defaults to `false` and does not affect layout.
     * @returns The stable identity used to find the entry later and its initial
     * wrapped height. Empty content still produces one logical empty line.
     *
     * @internal
     * @since 1.0.0
     */
    create(
        content: string,
        options?: { isError?: boolean }
    ): { id: symbol, height: number } {
        const startsAt = this.#_totalLines + 1;
        const entry = new ScreenEntry({
            content,
            startsAt,
            isError: options?.isError ?? false,
        });

        this.#_entries.push(entry);
        this.#_entriesLines += entry.height;

        return {
            id: entry.id,
            height: entry.height
        };
    }

    /**
     * Removes an entry and compacts every later entry toward line one.
     *
     * If `id` is unknown, no state changes and `null` is returned. A known entry
     * is removed and the aggregate height is reduced even when it was the last
     * entry; that case also returns `null` because no later entry positions need
     * adjustment. Otherwise, all following entries move up by the removed
     * entry's height. The returned half-open range begins at the removed
     * entry's former start and ends immediately after the last shifted entry,
     * covering the area the viewport must reconcile.
     *
     * @param id - Stable identity returned by {@link create}.
     * @returns The affected half-open logical line range, or `null` if the
     * identity is unknown or the removed entry was last. `null` does not mean
     * that a known last entry was left in the manager.
     *
     * @internal
     * @since 1.0.0
     */
    remove(id: symbol): Readonly<LinesRange> | null {
        const index = this.#_entries.findIndex(entry => entry.id === id);
        if (index === -1) { return null; }

        const currentEntry = this.#_entries[index];
        const removedLines = currentEntry.height;
        const isLastEntry = index === this.#_entries.length - 1;

        this.#_entriesLines -= removedLines;
        this.#_entries.splice(index, 1);

        if (isLastEntry) {
            return null;
        }

        const effectiveRange: LinesRange = {
            start: currentEntry.startsAt,
            end: currentEntry.startsAt + currentEntry.height
        }

        for (let i = index; i < this.#_entries.length; i++) {
            const entry = this.#_entries[i];
            entry.moveUp(removedLines);

            // On last entry, update the end index
            if (i === this.#_entries.length - 1) {
                effectiveRange.end = entry.startsAt + entry.height
            }
        }

        return Object.freeze(effectiveRange);
    }

    /**
     * Replaces one entry's complete content and repositions later entries if needed.
     *
     * The entry retains its identity and start line. Its wrapped lines are
     * rebuilt at the current terminal width. When its height changes, all
     * following entries move by the same absolute delta and the cached total is
     * adjusted. The returned range covers the updated entry and any following
     * entries whose starts shifted. An unknown identity returns `null` without
     * changing manager state.
     *
     * @param id - Stable identity of the entry to update.
     * @param content - Complete replacement content, not a partial fragment.
     * @returns A frozen half-open affected range with the updated entry's
     * `heightDelta`, or `null` if `id` is not managed. A zero delta still
     * returns a range for the updated entry.
     *
     * @internal
     * @since 1.0.0
     */
    update(id: symbol, content: string): EntryUpdateRange | null {
        const entryIndex = this.#_entries.findIndex(entry => entry.id === id);
        if (entryIndex === -1) { return null }

        const entry = this.#_entries[entryIndex];
        const heightChanged = entry.updateContent(content);
        const heightDelta = heightChanged
            ? entry.height - entry.lastHeight
            : 0;

        const affectedRange: LinesRange = {
            start: entry.startsAt,
            end: entry.startsAt + entry.height,
        }

        if (heightDelta !== 0) {
            this.#_entriesLines += heightDelta;

            const nextIndex = entryIndex + 1;
            if (nextIndex < this.#_entries.length) {
                const moveDirection = heightDelta > 0 ? 'Down' : 'Up';
                const moveAmount = Math.abs(heightDelta);

                for (let i = nextIndex; i < this.#_entries.length; i++) {
                    const nextEntry = this.#_entries[i];
                    nextEntry[`move${moveDirection}`](moveAmount);

                    // On last entry, update the end index
                    if (i === this.#_entries.length - 1) {
                        affectedRange.end = nextEntry.startsAt + nextEntry.height;
                    }
                }
            }
        }

        return Object.freeze({ ...affectedRange, heightDelta });
    }

    /**
     * Reflows every entry at the current terminal width and rebuilds positions.
     *
     * Entries are processed in their existing order. Each one reparses its
     * retained content, is assigned the first line after the previous entry,
     * and contributes its new height to a fresh aggregate. The aggregate is
     * replaced after the pass. This is a full logical reflow; it does not emit
     * terminal writes or return an affected range.
     *
     * @internal
     * @since 1.0.0
     */
    refresh(): void {
        let lines = 0;

        for (const entry of this.#_entries) {
            entry.refresh();
            entry.setStartsAt(lines + 1);
            lines += entry.height;
        }

        this.#_entriesLines = lines;
    }

    /**
     * Drops all managed entries and resets the aggregate logical height.
     *
     * The entry objects themselves are not mutated, removed through their cell
     * callbacks, or notified. References held elsewhere become unmanaged
     * because future identity lookups use this now-empty collection. The
     * viewport cache is reset separately by TOM after the caller clears the
     * screen.
     *
     * @internal
     * @since 1.0.0
     */
    clear() {
        this.#_entries.length = 0;
        this.#_entriesLines = 0;
    }

    /**
     * Exposes the manager's ordered backing array for viewport traversal.
     *
     * The returned value is the manager's actual mutable backing collection,
     * not a read-only wrapper or defensive copy. Consumers must treat it as
     * read-only; adding, removing, or reordering entries would bypass identity,
     * position, and total-height bookkeeping.
     *
     * @returns The live backing array in logical screen order.
     *
     * @internal
     * @since 1.0.0
     */
    get entries() { return this.#_entries; }
}

export default EntriesManager;